export function textoUI(valor) {
  const texto = String(valor ?? '—');
  if (Object.hasOwn(TEXTOS, texto)) return TEXTOS[texto];
  if (texto.startsWith('Ameaça iminente: separação prevista ')) return texto.replace('Ameaça iminente: separação prevista ', 'Imminent threat: predicted separation ').replace('mínimo ilustrativo', 'illustrative minimum');
  if (texto.startsWith('Pista insuficiente: ')) return texto.replace('Pista insuficiente: ', 'Runway too short: ').replace(' m para ', ' m available; ').replace(' m calculados.', ' m calculated.');
  if (texto.startsWith('Supervisor: ')) return `Supervisor: ${textoUI(texto.slice(12).replace(/\.$/, ''))}.`;
  return texto;
}
